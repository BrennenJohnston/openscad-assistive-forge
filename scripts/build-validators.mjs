#!/usr/bin/env node
/**
 * Write the app's data checks ahead of time.
 * @license GPL-3.0-or-later
 *
 * The schemas in src/js/validation-schema-defs.js are compiled here with
 * AJV's own standalone output into src/js/generated/validators.js, which is
 * committed. The page then imports plain functions and never compiles code
 * at run time, so its Content-Security-Policy needs no 'unsafe-eval'.
 *
 * Run it after changing a schema:
 *
 *   node scripts/build-validators.mjs
 *
 * tests/unit/validators-written.test.js writes the file again in memory and
 * fails when the committed copy differs.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import prettier from 'prettier';
import { AJV_OPTIONS, SCHEMAS } from '../src/js/validation-schema-defs.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const VALIDATORS_PATH = path.join(
  ROOT,
  'src',
  'js',
  'generated',
  'validators.js'
);

const HEADER = `/* eslint-disable */
// Generated by scripts/build-validators.mjs from the schemas in
// src/js/validation-schema-defs.js: AJV's own checks, written ahead of time
// so the page compiles no code at run time. Do not edit this file; run
// node scripts/build-validators.mjs after changing a schema.
`;

/** The one helper AJV's checks call, imported in place of its require(). */
const UCS2_REQUIRE = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g;
const UCS2_IMPORT = `import * as ucs2Module from 'ajv/dist/runtime/ucs2length.js';
const ucs2length =
  ucs2Module.default?.default ?? ucs2Module.default ?? ucs2Module;
`;

/**
 * The checks' source, as the file should hold it.
 * @returns {Promise<string>}
 */
export async function generateValidatorsSource() {
  const ajv = new Ajv({ ...AJV_OPTIONS, code: { source: true, esm: true } });
  const exportsByName = {};
  for (const [name, schema] of Object.entries(SCHEMAS)) {
    ajv.addSchema(schema, name);
    exportsByName[name] = name;
  }
  let code = standaloneCode(ajv, exportsByName);
  // A module is strict already; after the import the directive would be a
  // bare string.
  code = code.replace('"use strict";', '');
  const usesUcs2 = code.includes('ajv/dist/runtime/ucs2length');
  code = code.replace(UCS2_REQUIRE, 'ucs2length');
  if (/\brequire\(/.test(code)) {
    throw new Error('A require() is left in the written checks.');
  }
  if (/new Function\(|[^.\w$]eval\(/.test(code)) {
    throw new Error('The written checks would compile code at run time.');
  }
  const config = (await prettier.resolveConfig(VALIDATORS_PATH)) || {};
  return prettier.format(HEADER + (usesUcs2 ? UCS2_IMPORT : '') + code, {
    ...config,
    parser: 'babel',
    filepath: VALIDATORS_PATH,
  });
}

const invokedDirectly =
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (invokedDirectly) {
  const source = await generateValidatorsSource();
  fs.mkdirSync(path.dirname(VALIDATORS_PATH), { recursive: true });
  fs.writeFileSync(VALIDATORS_PATH, source);
  console.log(
    `Wrote ${path.relative(ROOT, VALIDATORS_PATH)} (${Object.keys(SCHEMAS).length} checks, ${source.length} characters).`
  );
}
